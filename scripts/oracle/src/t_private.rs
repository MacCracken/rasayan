/// The integer types a private scalar may have.
const INTS: [&str; 5] = ["usize", "u32", "u64", "u8", "i32"];

fn split(path: &str) -> (&str, Option<&str>, &str) {
    let parts: Vec<&str> = path.split("::").collect();
    match parts.as_slice() {
        [m, f, n] => (m, Some(f), n),
        [m, n] => (m, None, n),
        _ => ("", None, path),
    }
}

/// The Cyrius name of a private constant: `_RY_<MODULE>_<NAME>`.
pub fn cyr_name(path: &str) -> String {
    let (m, _, n) = split(path);
    format!("_RY_{}_{n}", m.to_uppercase())
}

/// Which emitter claims each `const` / `static` item, or why it is excused.
pub fn complete(root: &Path) -> Result<(), String> {
    let mut claims: BTreeMap<String, String> = BTreeMap::new();
    let mut claim = |path: String, who: &str| -> Result<(), String> {
        match claims.insert(path.clone(), who.to_string()) {
            Some(prev) => Err(format!("{path}: claimed by both {prev} and {who}")),
            None => Ok(()),
        }
    };
    for c in t_constants::all() {
        claim(c.path(), "t_constants")?;
    }
    for (module, list, who) in [
        ("protein", t_protein::GENERATED, "t_protein"),
        ("alignment", t_alignment::GENERATED, "t_alignment"),
        ("enzyme", t_enzyme::GENERATED, "t_enzyme"),
        ("membrane", t_membrane::GENERATED, "t_membrane"),
        ("ai", t_ai::GENERATED, "t_ai"),
    ] {
        for n in list {
            claim(format!("{module}::{n}"), who)?;
        }
    }
    for p in PRIVATE {
        claim((*p).to_string(), "t_private")?;
    }
    for (p, _, why) in EXCUSED {
        claim((*p).to_string(), &format!("excused: {why}"))?;
    }
    let mut found: Vec<Item> = Vec::new();
    for (module, path) in sources(root)? {
        let text =
            std::fs::read_to_string(&path).map_err(|e| format!("{}: {e}", path.display()))?;
        let src = Source::new(&module, &text)?;
        for item in items(&src)? {
            if let Some((_, want, _)) = EXCUSED.iter().find(|(p, ..)| *p == item.path()) {
                let got = src.text_of(item.expr.0, item.expr.1);
                if got != *want {
                    return Err(format!(
                        "{}: excused as `{want}`, but its initializer is now `{got}`",
                        item.path()
                    ));
                }
            }
            let who = claims.get(&item.path()).cloned().unwrap_or_default();
            let scalar = item.ty == "f64" || INTS.contains(&item.ty.as_str());
            if who == "t_constants" && !(item.public && scalar && item.in_fn.is_none()) {
                return Err(format!(
                    "{}: t_constants claims a non-public-scalar item",
                    item.path()
                ));
            }
            if who == "t_private" && (item.public || !scalar || item.is_static) {
                return Err(format!(
                    "{}: t_private claims a public or non-scalar item",
                    item.path()
                ));
            }
            found.push(item);
        }
    }
    let mut unclaimed = Vec::new();
    for item in &found {
        if claims.remove(&item.path()).is_none() {
            unclaimed.push(item.path());
        }
    }
    if !unclaimed.is_empty() || !claims.is_empty() {
        return Err(format!(
            "const/static items: not generated or excused {unclaimed:?}; claimed but not in \
             rust-old/src {:?}",
            claims.keys().collect::<Vec<_>>()
        ));
    }
    let mut names = BTreeMap::new();
    for p in PRIVATE {
        if let Some(prev) = names.insert(cyr_name(p), *p) {
            return Err(format!("{} would name both {prev} and {p}", cyr_name(p)));
        }
    }
    Ok(())
}

/// The number of `const` / `static` items in the library part of `rust-old/src`, and how many
/// are excused (for the README).
pub fn coverage(root: &Path) -> Result<(usize, usize), String> {
    let mut n = 0;
    for (module, path) in sources(root)? {
        let text =
            std::fs::read_to_string(&path).map_err(|e| format!("{}: {e}", path.display()))?;
        n += items(&Source::new(&module, &text)?)?.len();
    }
    Ok((n, EXCUSED.len()))
}

/// A private constant's value, from its initializer.
enum Scalar {
    F(f64),
    I(i128),
}

struct Private {
    path: String,
    item: Item,
    value: Scalar,
    comment: String,
    expr: String,
}

fn gather(root: &Path) -> Result<Vec<Private>, String> {
    let mut cache: BTreeMap<String, Source> = BTreeMap::new();
    let mut out = Vec::new();
    for p in PRIVATE {
        let (module, func, name) = split(p);
        if !cache.contains_key(module) {
            cache.insert(module.to_string(), Source::read(root, module)?);
        }
        let src = &cache[module];
        let ev = Eval::new(src)?;
        let item = match func {
            Some(fun) => ev.local_item(fun, name)?,
            None => ev.item(name)?,
        }
        .clone();
        let value = match (item.ty.as_str(), ev.value(&item)?) {
            ("f64", Val::F(x)) => Scalar::F(x),
            (ty, Val::I(x)) if INTS.contains(&ty) => Scalar::I(x),
            (ty, v) => return Err(format!("{p}: {ty} = {v:?}")),
        };
        let mut lines = src.comments_above(item.line);
        if let Some(t) = src.trailing(item.end_line) {
            lines.push(t);
        }
        out.push(Private {
            path: (*p).to_string(),
            expr: src.text_of(item.expr.0, item.expr.1),
            item,
            value,
            comment: comments(&lines),
        });
    }
    Ok(out)
}

pub fn emit(root: &Path, provenance: &str) -> Result<String, String> {
    complete(root)?;
    let mut out = header(
        "private constants (modules without a data file)",
        provenance,
        &[
            "Each is its initializer in rust-old/src, never re-typed: a literal parsed with Rust's\n\
             f64::from_str and written as a round-trip decimal, positionally; an expression folded as\n\
             Rust's const evaluation folds it. They are private to their module (_RY_<MODULE>_; a\n\
             fn-local const drops its fn). tests/golden/constants_private.tsv pins every value.",
            "The private constants of protein, alignment, enzyme, membrane and ai are in their\n\
             src/<module>_data.cyr.",
        ],
    );
    for p in gather(root)? {
        out.push_str(&p.comment);
        let _ = writeln!(
            out,
            "# Rust: rasayan::{} (private{}) = {}",
            p.path,
            if p.item.in_fn.is_some() {
                ", fn-local"
            } else {
                ""
            },
            p.expr
        );
        let lit = match p.value {
            Scalar::F(x) => f64_lit(x)?,
            Scalar::I(n) => n.to_string(),
        };
        let _ = writeln!(out, "const {} = {lit};\n", cyr_name(&p.path));
    }
    Ok(out.trim_end().to_string() + "\n")
}

/// constants_private.tsv: one `const` row per private constant, class A.
pub fn golden(root: &Path) -> Result<Module, String> {
    let mut m = Module::new("constants_private");
    for p in gather(root)? {
        let tok = match p.value {
            Scalar::F(x) => f(x),
            Scalar::I(n) => Tok::I(i64::try_from(n).map_err(|e| format!("{}: {e}", p.path))?),
        };
        m.row("const", Class::A, &[s(p.path.clone())], &[tok]);
    }
    Ok(m)
}
