//! `src/constants_private.cyr` and `tests/golden/constants_private.tsv` — the private scalar
//! constants of the modules without a data file — and the completeness proof for every `const`
//! and `static` item in `rust-old/src` (port plan §4 step 6). Adapted from ushma's `t_private.rs`.
//!
//! A private constant isn't reachable through the oracle's API, so its value comes from its
//! initializer in `rust-old/src` (`rustsrc.rs`: Rust's `f64::from_str` for the literals; the three
//! expressions, `calcium::CYTOSOL_ER_VOLUME_RATIO = 1.0 / ER_CYTOSOL_VOLUME_RATIO` and integrate's
//! `C1`–`C4` = `±1.0 / n`, folded as Rust's const evaluation folds them). Each has a `const` row in
//! `constants_private.tsv`, which `validate.py` re-derives with its own parser and the parity
//! harness checks against the compiled value. Names: `_RY_<MODULE>_<NAME>`, a fn-local const
//! without its fn (no two collide).
//!
//! `complete` proves that every `const` and `static` item of every module (outside its test
//! module; top level, in an `impl` and fn-local) is generated by exactly one emitter, or excused
//! with a reason, so an item added to the oracle can't be missed:
//! - public scalars: `src/constants.cyr` (`t_constants`);
//! - the tables and the private constants of protein, alignment, enzyme, membrane and ai: their
//!   `src/<module>_data.cyr` (`t_protein`, `t_alignment`, `t_enzyme`, `t_membrane`, `t_ai`);
//! - every other private constant: here;
//! - [`EXCUSED`]: three items, each pinned to its initializer's text.

